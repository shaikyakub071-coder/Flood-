def translate(lang, key, **values):
    """Text for `key` in `lang`. Falls back to English, then to the key."""
    text = TEXT.get(lang, {}).get(key)
    if text is None:
        text = TEXT["en"].get(key, key)
    if values:
        try:
            return text.format(**values)
        except (KeyError, IndexError):
            return text
    return text

